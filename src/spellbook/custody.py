_O_NOFOLLOW = getattr(os, "O_NOFOLLOW", 0)


class CustodyError(Exception):
    """Refusal with a message safe to show (never carries key material)."""


def warn(msg: str) -> None:
    print(f"SPELLBOOK CUSTODY WARNING (S-16): {msg}", file=sys.stderr, flush=True)


def _now_iso() -> str:
    return datetime.datetime.now(datetime.timezone.utc).strftime(
        "%Y-%m-%dT%H:%M:%SZ")


def _geteuid() -> int:
    return os.geteuid() if hasattr(os, "geteuid") else -1


# ---------------------------------------------------------------- locations

def ceremony_dir(prefix: str) -> str:
    return os.path.join(prefix, CEREMONY_DIR)


def ceremony_key_path(prefix: str) -> str:
    return os.path.join(ceremony_dir(prefix), CEREMONY_KEY)


def backup_state_path(prefix: str) -> str:
    return os.path.join(prefix, BACKUP_STATE)


def prefix_owner(prefix: str) -> int:
    return os.stat(prefix).st_uid


def load_cfg(prefix: str) -> dict | None:
    try:
        with open(os.path.join(prefix, "spellbook.json")) as f:
            cfg = json.load(f)
    except FileNotFoundError:
        return None
    return cfg if isinstance(cfg, dict) else None


def agent_uids(cfg: dict | None) -> list[int]:
    uids = (cfg or {}).get("allowed_request_uids") or []
    return [u for u in uids if isinstance(u, int) and not isinstance(u, bool)]


def legacy_key_path(cfg: dict | None) -> str:
    return os.path.expanduser((cfg or {}).get("ceremony_key_path")
                              or LEGACY_KEY_PATH)


def agent_reach_reason(path: str, agent_uid_list, daemon_uid: int) -> str | None:
    """Why `path` is within the agent's reach, or None when it is not.

    In reach: the daemon itself runs as an agent uid; or the path or any
    existing ancestor is owned by an agent uid (the agent can read, rename
    or replace it); or an ancestor directory is world-writable without the
    sticky bit. Group membership is not modelled: the daemon's own dirs
    are created 0700, and the read checks refuse group/other bits.
    """
    agents = set(agent_uid_list or [])
    if daemon_uid in agents:
        return (f"the daemon runs as the agent's OS user (uid {daemon_uid}): "
                "this host has no custody separation")
    cur = os.path.abspath(path)
    while True:
        try:
            st = os.lstat(cur)
        except FileNotFoundError:
            st = None
        if st is not None:
            if st.st_uid in agents:
                return f"{cur} is owned by the agent's OS user (uid {st.st_uid})"
            if (stat.S_ISDIR(st.st_mode) and st.st_mode & 0o002
                    and not st.st_mode & stat.S_ISVTX):
                return f"{cur} is world-writable"
        parent = os.path.dirname(cur)
        if parent == cur:
            return None
        cur = parent


# ---------------------------------------------------------------- key files

def _chown_like_prefix(path: str, prefix: str) -> None:
    if _geteuid() == 0:
        st = os.stat(prefix)
        os.chown(path, st.st_uid, st.st_gid)


def _ensure_private_dir(prefix: str) -> str:
    d = ceremony_dir(prefix)
    try:
        os.mkdir(d, 0o700)
    except FileExistsError:
        pass
    st = os.lstat(d)
    if not stat.S_ISDIR(st.st_mode):
        raise CustodyError(f"{d} is not a directory — refusing")
    os.chmod(d, 0o700)
    _chown_like_prefix(d, prefix)
    return d


def _write_exclusive(path: str, data: bytes, mode: int, prefix: str) -> None:
    """Write `data` to a fresh temp file (O_EXCL, `mode` from creation),
    fsync it, hand it to the prefix owner when root, then rename over
    `path` — no window with loose modes, never through a symlink."""
    tmp = f"{path}.tmp-{secrets.token_hex(4)}"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL | _O_NOFOLLOW, mode)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        os.chmod(tmp, mode)
        _chown_like_prefix(tmp, prefix)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def _check_runner(prefix: str, cfg: dict | None) -> None:
    """Key generation and adoption run as root or as the prefix owner (the
    daemon user), never as the agent's OS user."""
    euid = _geteuid()
    owner = prefix_owner(prefix)
    if euid not in (0, owner):
        raise CustodyError(
            f"run this as root or as the daemon user that owns {prefix} "
            "(e.g. `sudo spellbook ...`), not as uid "
            f"{euid}")
    if euid != 0 and euid in agent_uids(cfg):
        raise CustodyError(
            "the daemon user is the agent's OS user: the agent would hold the "
            "ceremony key (S-16). The passwordless ceremony needs the "
            "install.sh daemon-user split")


def _public_b64(key) -> tuple[str, str]:
    der = key.publickey().export_key(format="DER")  # SubjectPublicKeyInfo
    return base64.b64encode(der).decode(), key_fingerprint(der)


def key_fingerprint(der: bytes) -> str:
    """Full sha256 hex of the SPKI DER: what the ceremony pages show and
    ask the human to match (spellbook.ceremony.key_fingerprint)."""
    return hashlib.sha256(der).hexdigest()


def grouped(fp: str) -> str:
    return " ".join(fp[i:i + 4] for i in range(0, len(fp), 4))


def _write_public(prefix: str, key) -> str:
    pub, _ = _public_b64(key)
    d = ceremony_dir(prefix)
    _write_exclusive(os.path.join(d, CEREMONY_PUB), pub.encode(), 0o644, prefix)
    _write_exclusive(os.path.join(d, CEREMONY_PUB_PEM),
                     key.publickey().export_key(format="PEM"), 0o644, prefix)
    return pub


def _write_meta(prefix: str, origin: str) -> None:
    meta = {"origin": origin, "at": _now_iso()}
    _write_exclusive(os.path.join(ceremony_dir(prefix), CEREMONY_META),
                     json.dumps(meta, sort_keys=True).encode(), 0o600, prefix)


def key_origin(prefix: str) -> str | None:
    try:
        with open(os.path.join(ceremony_dir(prefix), CEREMONY_META)) as f:
            return json.load(f).get("origin")
    except (OSError, ValueError, AttributeError):
        return None


def generate_ceremony_key(prefix: str, *, rotate: bool = False) -> dict:
    """Create the daemon's ceremony keypair, or report the existing one.

    Returns {"public_key_b64", "fingerprint", "created"} — public material
    only. Rotating makes every envelope sealed to the old key unreadable,
    so it also marks the backup required (the next seed is a new one).
    """
    cfg = load_cfg(prefix)
    _check_runner(prefix, cfg)
    path = ceremony_key_path(prefix)
    if os.path.lexists(path) and not rotate:
        key = read_private_key(path, prefix_owner(prefix))
        pub, fp = _public_b64(key)
        return {"public_key_b64": pub, "fingerprint": fp, "created": False}
    from Crypto.PublicKey import RSA
    _ensure_private_dir(prefix)
    key = RSA.generate(2048)
    _write_exclusive(path, key.export_key(format="PEM", pkcs=8), 0o600, prefix)
    pub, fp = _public_b64(key)
    _write_public(prefix, key)
    _write_meta(prefix, "generated")
    if rotate:
        require_backup(prefix)
    return {"public_key_b64": pub, "fingerprint": fp, "created": True}


def public_key_info(prefix: str) -> dict | None:
    """The daemon's ceremony PUBLIC key, as written beside the private one."""
    try:
        with open(os.path.join(ceremony_dir(prefix), CEREMONY_PUB)) as f:
            pub = f.read().strip()
        der = base64.b64decode(pub, validate=True)
    except (OSError, ValueError):
        return None
    return {"public_key_b64": pub,
            "fingerprint": key_fingerprint(der)}


def public_pem(prefix: str) -> bytes:
    """The daemon's ceremony PUBLIC key as PEM (for publishing)."""
    info = public_key_info(prefix)
    if info is None:
        raise CustodyError("no ceremony public key: run `spellbook ceremony-key`")
    from Crypto.PublicKey import RSA
    return RSA.import_key(base64.b64decode(info["public_key_b64"])).export_key(format="PEM")


def read_private_key(path: str, owner_uid: int, *, strict: bool = True):
    """Load an RSA private key, refusing loose custody.

    strict (the daemon's own key): opened without following symlinks; the
    file and its directory must be owned by `owner_uid` and carry no
    group/other bits. Non-strict (a legacy key, read once to move it or as
    a warned fallback): the file must be 0600, as the old loader required.
    """
    from Crypto.PublicKey import RSA
    fd = os.open(path, os.O_RDONLY | _O_NOFOLLOW)
    try:
        st = os.fstat(fd)
        if not stat.S_ISREG(st.st_mode):
            raise CustodyError(f"ceremony key at {path} is not a regular file")
        if st.st_mode & 0o077:
            raise CustodyError(f"ceremony key at {path} is not 0600 — refusing")
        if strict:
            dst = os.lstat(os.path.dirname(os.path.abspath(path)))
            if st.st_uid != owner_uid or dst.st_uid != owner_uid:
                raise CustodyError(
                    f"ceremony key at {path} is not owned by the daemon user "
                    f"(uid {owner_uid}) — refusing")
            if dst.st_mode & 0o077 or not stat.S_ISDIR(dst.st_mode):
                raise CustodyError(
                    f"{os.path.dirname(path)} is not a 0700 directory — refusing")
        data = b""
        while True:
            chunk = os.read(fd, 65536)
            if not chunk:
                break
            data += chunk
    finally:
        os.close(fd)
    try:
        key = RSA.import_key(data)
    except (ValueError, IndexError, TypeError):
        raise CustodyError(f"ceremony key at {path} is not an RSA private key")
    if not key.has_private() or key.size_in_bits() < 2048:
        raise CustodyError(f"ceremony key at {path} is not an RSA-2048+ private key")
    return key


def secure_remove(path: str) -> dict:
    """Overwrite `path` in place with random bytes, fsync, then unlink.

    Best effort, and says what happened: {"overwritten", "unlinked"}.
    Overwriting cannot reach blocks a journaling or copy-on-write
    filesystem, an SSD, a snapshot or a backup kept elsewhere.
    """
    out = {"overwritten": False, "unlinked": False}
    try:
        fd = os.open(path, os.O_WRONLY | _O_NOFOLLOW)
        try:
            size = os.fstat(fd).st_size
            os.write(fd, os.urandom(max(size, 1)))
            os.fsync(fd)
            out["overwritten"] = True
        finally:
            os.close(fd)
    except OSError:
        pass
    try:
        os.unlink(path)
        out["unlinked"] = True
    except OSError:
        pass
    return out


def adopt_ceremony_key(prefix: str, src: str, *, check_runner: bool = True) -> dict:
    """MOVE a ceremony key out of agent reach into <prefix>/ceremony/.

    Refuses when the destination itself is in agent reach (no daemon-user
    split): moving the key within the agent's own files closes nothing and
    could lose it on a VM wipe. Returns {"moved_to", "overwritten",
    "unlinked"} (see secure_remove for what those guarantee).
    """
    cfg = load_cfg(prefix)
    if check_runner:
        _check_runner(prefix, cfg)
    dest = ceremony_key_path(prefix)
    owner = prefix_owner(prefix)
    reason = agent_reach_reason(ceremony_dir(prefix), agent_uids(cfg), owner)
    if reason:
        raise CustodyError(f"the daemon's own dir is in agent reach: {reason}")
    src = os.path.abspath(os.path.expanduser(src))
    if os.path.exists(dest) and os.path.samefile(src, dest):
        return {"moved_to": dest, "overwritten": False, "unlinked": False}
    key = read_private_key(src, owner, strict=False)
    pem = key.export_key(format="PEM", pkcs=8)
    if os.path.lexists(dest):
        mine = read_private_key(dest, owner)
        if mine.publickey().export_key(format="DER") != \
                key.publickey().export_key(format="DER"):
            raise CustodyError(
                f"the daemon already holds a different ceremony key at {dest}; "
                f"{src} was left in place — the human decides which envelope "
                "is live")
    else:
        _ensure_private_dir(prefix)
        _write_exclusive(dest, pem, 0o600, prefix)
        _write_public(prefix, key)
        _write_meta(prefix, "adopted")
    # Read back before destroying the only other copy.
    if read_private_key(dest, owner).export_key(format="PEM", pkcs=8) != pem:
        raise CustodyError(f"read-back of {dest} failed; {src} left in place")
    res = secure_remove(src)
    res["moved_to"] = dest
    return res


# ---------------------------------------------------------------- envelope

def decrypt_envelope(envelope: str, key, *, allow_custom: bool = False) -> bytes:
    """SPELLBOOK-SEED-ENC2 -> the 64-byte standard seed (or, with
    allow_custom, a 32-byte custom seed too). Fails closed."""
    from Crypto.Cipher import AES, PKCS1_OAEP
    from Crypto.Hash import SHA256
    envelope = envelope.strip()
    if not envelope.startswith(ENVELOPE_PREFIX):
        raise ValueError("sealed envelope has wrong prefix — refusing")
    try:
        payload = json.loads(base64.b64decode(envelope.split(".", 1)[1]))
    except Exception as e:
        raise ValueError(f"sealed envelope is not valid JSON: {type(e).__name__}")
    if not isinstance(payload, dict) or payload.get("v") != 2 \
            or payload.get("algo") != ENVELOPE_ALGO:
        raise ValueError("unsupported envelope version/algorithm — refusing")
    try:
        # RSA-OAEP with SHA-256 and MGF1-SHA-256, as WebCrypto wraps it.
        aes_key = PKCS1_OAEP.new(key, hashAlgo=SHA256).decrypt(
            bytes.fromhex(payload["ek"]))
        blob = bytes.fromhex(payload["ct"])
        if len(blob) < 16:
            raise ValueError("short ciphertext")
        c = AES.new(aes_key, AES.MODE_GCM, nonce=bytes.fromhex(payload["iv"]))
        seed_hex = c.decrypt_and_verify(blob[:-16], blob[-16:]) \
            .decode().strip().lower()
    except Exception as e:
        raise ValueError(f"envelope decryption failed: {type(e).__name__}")
    sizes = (128, 64) if allow_custom else (128,)
    if len(seed_hex) not in sizes or not all(c in "0123456789abcdef" for c in seed_hex):
        raise ValueError(
            "envelope did not contain a 128-char standard seed — refusing")
    return bytes.fromhex(seed_hex)


def _read_envelope(path: str) -> str:
    if not os.path.exists(path):
        raise FileNotFoundError(
            f"sealed envelope not found at {path} — cannot load sealed seed")
    if os.stat(path).st_mode & 0o077:
        raise PermissionError(
            f"sealed envelope at {path} is not 0600 — refusing to load")
    with open(path) as f:
        return f.read()


def load_envelope_seed(prefix: str, cfg: dict, *, adopt: bool = True) -> tuple[bytes, dict]:
    """Decrypt cfg["sealed_envelope_path"] with the daemon's own key.

    Returns (seed64, info). info = {"key_source": "daemon" | "agent-reach",
    "key_origin", "separation": "ok" | <reason>, "warnings": [...]}. A
    legacy key in agent reach is moved first when the daemon has a dir of
    its own (adopt=True); otherwise it is used with a loud warning, so an
    existing install keeps starting.
    """
    envelope_path = os.path.expanduser(cfg["sealed_envelope_path"])
    euid = _geteuid()
    owner = prefix_owner(prefix)
    agents = agent_uids(cfg)
    own = ceremony_key_path(prefix)
    legacy = legacy_key_path(cfg)
    warnings = []
    sep = agent_reach_reason(ceremony_dir(prefix), agents,
                             owner if euid == 0 else euid)
    legacy_live = os.path.lexists(legacy) and not (
        os.path.exists(own) and os.path.exists(legacy)
        and os.path.samefile(own, legacy))
    if legacy_live and adopt:
        if sep is None:
            try:
                res = adopt_ceremony_key(prefix, legacy, check_runner=False)
                warnings.append(
                    f"moved the ceremony key from {legacy} into {own} "
                    f"(original overwritten: {res['overwritten']}, unlinked: "
                    f"{res['unlinked']}). It was in agent reach: re-seed when "
                    "practical.")
                if not res["unlinked"]:
                    warnings.append(
                        f"could not unlink {legacy}; root removes it: "
                        "`sudo spellbook ceremony-adopt`")
            except (CustodyError, OSError) as e:
                warnings.append(f"could not move the ceremony key at {legacy} "
                                f"out of agent reach: {e}")
        else:
            warnings.append(
                f"the ceremony key at {legacy} is in agent reach and stays "
                f"there: {sep}")
    envelope = _read_envelope(envelope_path)
    if not os.path.lexists(own) and not os.path.lexists(legacy):
        raise FileNotFoundError(
            f"ceremony private key not found at {own} — cannot load sealed "
            "seed. Generate it as the daemon user (`sudo spellbook "
            "ceremony-key`) and re-run the ceremony with its public key.")
    seed, source, origin = None, None, None
    if os.path.lexists(own):
        key = read_private_key(own, owner)
        try:
            seed = decrypt_envelope(envelope, key)
            source, origin = "daemon", key_origin(prefix) or "generated"
        except ValueError:
            if not os.path.lexists(legacy):
                raise
    if seed is None:
        # Only a key still in agent reach opens this envelope (an old
        # ceremony whose key could not be moved). Keep the wallet running,
        # loudly: refusing here would strand a working install.
        key = read_private_key(legacy, owner, strict=False)
        seed = decrypt_envelope(envelope, key)
        source, origin = "agent-reach", "legacy"
        warnings.append(
            f"DECRYPTING THE LIVE SEED WITH A KEY IN AGENT REACH ({legacy}). "
            "Anything running as the agent can decrypt the seed without the "
            "daemon. Move it: `sudo spellbook ceremony-adopt --prefix "
            f"{prefix}`, then re-seed when practical.")
    if sep is not None and source == "daemon":
        warnings.append(f"the daemon's ceremony key is in agent reach: {sep}")
    return seed, {"key_source": source, "key_origin": origin,
                  "separation": "ok" if sep is None else sep,
                  "warnings": warnings}


def live_seed(prefix: str) -> tuple[bytes | None, str]:
    """The seed the daemon signs with, loaded the way the daemon loads it.

    Returns (seed or None, "standard" | "kdf"). Without a spellbook.json
    (tests, a bare prefix) the mode is inferred from the files present.
    """
    from spellbook.seed import load_seed, load_std_seed
    cfg = load_cfg(prefix)
    if cfg is None:
        kd = "standard" if os.path.exists(
            os.path.join(prefix, "std_seed.key")) else "kdf"
    else:
        kd = cfg.get("key_derivation", "kdf")
    if kd == "standard":
        p = os.path.expanduser((cfg or {}).get("std_seed_path")
                               or os.path.join(prefix, "std_seed.key"))
        if os.path.exists(p):
            return load_std_seed(p), kd
        if cfg and cfg.get("sealed_envelope_path"):
            return load_envelope_seed(prefix, cfg, adopt=False)[0], kd
        return None, kd
    p = os.path.expanduser((cfg or {}).get("seed_path")
                           or os.path.join(prefix, "seed.key"))
    return (load_seed(p) if os.path.exists(p) else None), kd


# ---------------------------------------------------------------- backup state

def seed_fingerprint(seed: bytes) -> str:
    """Names the seed a confirmation covers; reveals nothing usable."""
    return hashlib.sha256(_FP_TAG + seed).hexdigest()[:32]


def read_backup_state(prefix: str) -> dict | None:
    """The backup record, or None when there is none (an install made before
    forced backup). A record that is not a regular file owned by the
    prefix owner (or root), or does not parse, reads as REQUIRED and
    unconfirmed: fail closed."""
    path = backup_state_path(prefix)
    try:
        fd = os.open(path, os.O_RDONLY | _O_NOFOLLOW)
    except FileNotFoundError:
        return None
    except OSError:
        return {"required": True, "invalid": "unreadable"}
    try:
        st = os.fstat(fd)
        with os.fdopen(fd) as f:
            text = f.read()
    except OSError:
        return {"required": True, "invalid": "unreadable"}
    if not stat.S_ISREG(st.st_mode) or st.st_uid not in (0, prefix_owner(prefix)) \
            or st.st_mode & 0o022:
        return {"required": True, "invalid": "not owned by the daemon user"}
    try:
        doc = json.loads(text)
    except ValueError:
        return {"required": True, "invalid": "not JSON"}
    return doc if isinstance(doc, dict) else {"required": True, "invalid": "shape"}


def _write_backup_state(prefix: str, doc: dict) -> None:
    _write_exclusive(backup_state_path(prefix),
                     (json.dumps(doc, indent=1, sort_keys=True) + "\n").encode(),
                     0o600, prefix)


def require_backup(prefix: str) -> dict:
    """Mark this install backup-pending until a confirmation names its seed."""
    doc = read_backup_state(prefix) or {}
    doc.pop("invalid", None)
    if not doc.get("required"):
        doc["required"] = True
        doc["required_since"] = _now_iso()
        _write_backup_state(prefix, doc)
    return doc


def confirm_backup(prefix: str, fingerprint: str, method: str) -> dict:
    doc = read_backup_state(prefix) or {}
    doc.pop("invalid", None)
    doc.pop("pending_code", None)
    doc["required"] = True
    doc["backup_confirmed_at"] = _now_iso()
    doc["fingerprint"] = fingerprint
    doc["method"] = method
    _write_backup_state(prefix, doc)
    return doc


def backup_status(prefix: str, live_fp: str | None) -> dict:
    """{"state": "confirmed" | "pending" | "legacy", ...}.

    legacy: no record, or one never marked required (installs made before
    forced backup) — fund routes stay open, with a warning. pending: required
    and no confirmation for THIS seed (a swapped seed is unconfirmed too).
    """
    doc = read_backup_state(prefix)
    if doc is None:
        return {"state": "legacy"}
    confirmed = (live_fp is not None and doc.get("backup_confirmed_at")
                 and isinstance(doc.get("fingerprint"), str)
                 and hmac.compare_digest(doc["fingerprint"], live_fp)
                 and not doc.get("invalid"))
    if confirmed:
        return {"state": "confirmed",
                "backup_confirmed_at": doc["backup_confirmed_at"],
                "method": doc.get("method")}
    if not doc.get("required") and not doc.get("invalid"):
        return {"state": "legacy"}
    out = {"state": "pending"}
    if doc.get("invalid"):
        out["reason"] = f"backup record {doc['invalid']}"
    elif doc.get("backup_confirmed_at"):
        out["reason"] = "the confirmed backup is for a different seed"
    return out


def pending_message(prefix: str) -> str:
    return (
        "backup pending: the human has not yet proven they hold this wallet's "
        "recovery words (review S-16), so fund-moving routes are refused; "
        "read-only routes still work. The HUMAN runs, at their own terminal: "
        f"`sudo spellbook export --prefix {prefix}` (shows the words, asks "
        "3 back). If they can only reach you: `sudo spellbook export --prefix "
        f"{prefix} --reveal-key <their page's public key>`, they decrypt it on "
        "their page, write the words down, and give you the confirmation code "
        f"inside it for `sudo spellbook backup-confirm --prefix {prefix}`.")


# ---------------------------------------------------------------- one-time code

def _norm_code(code: str) -> str:
    return "".join(ch for ch in str(code).upper() if ch.isalnum())


def _code_hash(code: str, fingerprint: str) -> str:
    return hashlib.sha256(b"spellbook-backup-code/v1|" + fingerprint.encode()
                          + b"|" + _norm_code(code).encode()).hexdigest()


def issue_backup_code(prefix: str, fingerprint: str) -> str:
    """A one-time code for the encrypted backup (reveal-key path).

    Only its hash is stored. Issuing never flips an install into
    backup-pending (an existing install stays as it is)."""
    code = "-".join("".join(secrets.choice(_CODE_ALPHABET) for _ in range(4))
                    for _ in range(4))
    doc = read_backup_state(prefix) or {"required": False}
    doc.pop("invalid", None)
    doc["pending_code"] = {"sha256": _code_hash(code, fingerprint),
                           "fingerprint": fingerprint,
                           "expires": int(time.time()) + CODE_TTL_S,
                           "attempts": 0}
    _write_backup_state(prefix, doc)
    return code


def confirm_with_code(prefix: str, code: str, live_fp: str) -> tuple[bool, str]:
    doc = read_backup_state(prefix)
    pc = (doc or {}).get("pending_code")
    if not isinstance(pc, dict):
        return False, ("no confirmation code is outstanding: run `spellbook "
                       "export --reveal-key` first")
    if pc.get("fingerprint") != live_fp:
        return False, "the code was issued for a different seed; export again"
    if int(pc.get("expires", 0)) < time.time():
        doc.pop("pending_code", None)
        _write_backup_state(prefix, doc)
        return False, "the code expired; export again"
    if not hmac.compare_digest(pc.get("sha256", ""), _code_hash(code, live_fp)):
        pc["attempts"] = int(pc.get("attempts", 0)) + 1
        if pc["attempts"] >= CODE_MAX_ATTEMPTS:
            doc.pop("pending_code", None)
            _write_backup_state(prefix, doc)
            return False, "wrong code; too many attempts — export again"
        _write_backup_state(prefix, doc)
        return False, "wrong code"
    confirm_backup(prefix, live_fp, "reveal-key-code")
    return True, "backup confirmed"
