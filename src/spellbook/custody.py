"""Daemon-side custody of the ceremony key, and the forced backup (review S-16).

The passwordless ceremony (ceremony/seed-to-addresses.html) seals the
human's standard seed into a SPELLBOOK-SEED-ENC2 envelope: AES-256-GCM,
key wrapped with RSA-OAEP-SHA256 to a ceremony public key. The daemon
decrypts that envelope at every start, so the wallet survives restarts
with no password.

Before this module the AGENT minted the RSA key and kept private.pem in
its own workspace, next to the envelope, so the agent could decrypt the
live seed whenever it liked. Now:

  key       The decrypting key is generated by the daemon's OS user (or by
            root, which hands it to that user) inside the daemon's own
            config dir: <prefix>/ceremony/private.pem, file 0600, directory
            0700. Only the PUBLIC key leaves it — `spellbook ceremony-key`
            prints it, `spellbook status` reports it — and the agent stamps
            that public key into the page the human opens. The envelope
            itself may stay anywhere, including in agent reach: it is
            ciphertext to a key the agent cannot read.

  legacy    A ceremony key left in agent reach by the old ceremony
            (cfg ceremony_key_path, default
            ~/workspace/.spellbook/seed-derive/private.pem) is MOVED into
            the daemon's dir and the original is overwritten and unlinked
            (`spellbook ceremony-adopt`, run by root; the daemon also tries
            at start). Guaranteed: the original path no longer names the
            key, and its file contents were overwritten in place when the
            file was writable. NOT guaranteed: that the old bytes are gone
            from the disk (journaling and copy-on-write filesystems, SSD
            remapping, snapshots, backups), or that the agent did not copy
            the key earlier. A key that has ever been in agent reach should
            be treated as exposed: re-seed when practical.

  backup    A fresh install (and any seed loaded through a daemon-generated
            ceremony key) is BACKUP-PENDING until the human proves they hold
            the words: `spellbook export` on their own terminal (the words,
            then 3 of them typed back) or `spellbook export --reveal-key`
            followed by `spellbook backup-confirm` with the one-time code
            that is inside the encrypted backup. The proof is recorded in
            <prefix>/backup.json, written only by those commands (root or
            the daemon user) and bound to a fingerprint of the live seed. No
            daemon route writes it, so the request token cannot set it.
            While pending, the daemon refuses every fund-moving route and
            keeps the read-only ones.

Honest limit: when the daemon runs as the agent's own OS user (agent-VM
mode, no `spellbook` user), there is no custody separation for software
to enforce. The daemon then leaves the key where it is (moving it inside
the agent's own files changes nothing and could lose it on a VM wipe) and
warns loudly on every start.

Nothing in this module prints, logs or returns seed, key or code material.
"""
