# ------------------------------------------------------------ paper backup text

def _word_runs(text):
    return [l.split() for l in text.splitlines()
            if len(l.split()) == 24 and all(w in WORDS for w in l.split())]


def test_paper_backup_text_is_words_and_addresses_never_raw_keys():
    kdf_seed, std_entropy = os.urandom(32), os.urandom(32)
    text = exportmod.paper_backup_text(kdf_seed, std_entropy)
    assert "SET 1" in text and "SET 2" in text
    assert kdf_seed.hex() not in text and std_entropy.hex() not in text
    assert not re.search(r"\b[0-9a-fA-F]{64,}\b", text)
    assert not re.search(r"\b[1-9A-HJ-NP-Za-km-z]{80,}\b", text)
    assert len(_word_runs(text)) == 2


def test_paper_backup_text_handles_a_restored_install():
    text = exportmod.paper_backup_text(os.urandom(32), None, with_addresses=False,
                                       std_words_lost=True)
    assert "SET 2" in text and "not shown" in text and len(_word_runs(text)) == 1
    with pytest.raises(ValueError):
        exportmod.paper_backup_text(None, None)


# ------------------------------------------------------------ reveal-key envelope

def _reveal_keypair(bits=2048):
    from Crypto.PublicKey import RSA
    key = RSA.generate(bits)
    pub = key.public_key().export_key(format="DER")  # SubjectPublicKeyInfo
    return key, base64.b64encode(pub).decode()


def _open_envelope(priv, envelope):
    # Mirrors ceremony/seal-password-encryptor.html Step 2 (WebCrypto
    # RSA-OAEP SHA-256 + AES-GCM with the tag appended).
    from Crypto.Cipher import AES, PKCS1_OAEP
    from Crypto.Hash import SHA256
    env = json.loads(base64.b64decode(envelope))
    aes = PKCS1_OAEP.new(priv, hashAlgo=SHA256).decrypt(base64.b64decode(env["k"]))
    blob = base64.b64decode(env["c"])
    c = AES.new(aes, AES.MODE_GCM, nonce=base64.b64decode(env["n"]))
    return c.decrypt_and_verify(blob[:-16], blob[-16:]).decode()


def test_export_to_a_reveal_key_prints_only_the_envelope(tmp_path):
    prefix, kdf_seed, std_entropy = _install_dir(tmp_path)
    priv, pub_b64 = _reveal_keypair()
    r = _cli(["export", "--prefix", str(prefix), "--reveal-key", "-"],
             input_text=pub_b64)
    assert r.returncode == 0, r.stderr
    envelope = r.stdout.strip()
    assert "\n" not in envelope and r.stderr == ""
    for secret in (mnemonic_from_entropy(std_entropy), mnemonic_from_entropy(kdf_seed),
                   kdf_seed.hex(), std_entropy.hex()):
        assert secret not in r.stdout
    doc = _open_envelope(priv, envelope)
    assert mnemonic_from_entropy(std_entropy) in doc
    assert mnemonic_from_entropy(kdf_seed) in doc
    assert not re.search(r"\b[0-9a-fA-F]{64,}\b", doc), "raw key in the envelope"
    assert "Press Enter" not in doc


def test_reveal_key_must_be_rsa_2048_or_more():
    from Crypto.PublicKey import ECC
    ec_pub = ECC.generate(curve="P-256").public_key().export_key(format="DER")
    priv, _ = _reveal_keypair(2048)
    priv_der = base64.b64encode(priv.export_key(format="DER")).decode()
    _, small = _reveal_keypair(1024)
    for bad in ("", "not base64!", base64.b64encode(ec_pub).decode(), small, priv_der):
        with pytest.raises(ValueError):
            exportmod.seal_to_reveal_key("x", bad)


# ------------------------------------------------------------ terminal mode

def test_check_words_and_positions():
    m = mnemonic_from_entropy(os.urandom(32))
    w = m.split()
    assert exportmod.check_words(m, [1, 5, 24], [w[0], " " + w[4].upper(), w[23]])
    assert not exportmod.check_words(m, [1, 5, 24], [w[0], w[4], "zzz"])
    assert not exportmod.check_words(m, [1, 5, 24], [w[0], "ü", w[23]])
    pos = exportmod.verification_positions()
    assert len(set(pos)) == 3 and all(1 <= p <= 24 for p in pos)


@pytest.mark.skipif(not POSIX, reason="needs a pty")
def test_terminal_export_writes_words_to_the_tty_never_stdout(tmp_path, monkeypatch, capsys):
    prefix, kdf_seed, std_entropy = _install_dir(tmp_path)
    master, slave = os.openpty()
    tty_path = os.ttyname(slave)
    words = mnemonic_from_entropy(std_entropy).split()
    os.write(master, ("\n" + "\n".join([words[0], words[1], words[2]]) + "\n").encode())
    monkeypatch.setattr(sys.stdin, "isatty", lambda: True, raising=False)
    monkeypatch.setattr(sys.stdout, "isatty", lambda: True, raising=False)
    monkeypatch.setattr(exportmod, "login_uid", lambda: 4242)
    monkeypatch.setattr(exportmod, "verification_positions", lambda *a, **k: [1, 2, 3])
    monkeypatch.setattr(exportmod.shutil, "which", lambda name: None)
    rc = exportmod.run_export(str(prefix), tty_path=tty_path)
    out = capsys.readouterr()
    assert rc == 0, out.err
    assert "SET 1 verified" in out.out
    _assert_no_secret_material(out.out + out.err)
    seen = b""
    while select.select([master], [], [], 0.2)[0]:
        chunk = os.read(master, 65536)
        if not chunk:
            break
        seen += chunk
    os.close(master)
    os.close(slave)
    tty_text = seen.decode(errors="replace")
    assert mnemonic_from_entropy(std_entropy) in tty_text
    assert mnemonic_from_entropy(kdf_seed) in tty_text
    assert exportmod.CLEAR_SEQUENCE in tty_text
    # cleared after the words, and again after the typed answers
    assert tty_text.rindex(exportmod.CLEAR_SEQUENCE) > tty_text.index("Word #3")


# ------------------------------------------------------------ install.sh

def test_installer_never_echoes_secrets():
    sh = open(os.path.join(ROOT, "install.sh"), encoding="utf-8").read()
    for gone in ("STD_BACKUP", "MNEMONIC=", "KDF_KEYS", "REQ_TOKEN=", "APP_TOKEN=",
                 "PAPER_TXT", 'cat "${PAPER_TXT}"', "mnemonic_from_entropy",
                 "scalar_hex", "phantom_backup_secret", "SPELLBOOK_REQUEST_TOKEN=",
                 "STD_MNEMONIC"):
        assert gone not in sh, gone
    assert "[ -t 0 ] && [ -t 1 ]" in sh
    assert 'spellbook" export --prefix' in sh
    assert "--reveal-key" in sh
    assert "make_tokens.py" in sh
    assert 'chown "${AGENT_USER}" "${AGENT_TOKEN_FILE}"' in sh
    assert 'chmod 0600 "${AGENT_TOKEN_FILE}"' in sh
    # set -u: an install without --restore must not die on an unset variable
    assert 'RESTORE_FILE=""' in sh
