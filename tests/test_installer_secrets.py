"""S-05: the installer's scripts print no secret, and the paper backup is a
human-only, terminal-only export.

The wallet scripts run as subprocesses with stdin/stdout as pipes (what an
agent, CI or `script` sees) against throwaway files in a temp dir. Every
seed here is generated by the script under test or inside the test.
"""
import os
import re
import stat
import subprocess
import sys

import pytest

from spellbook import export as exportmod
from spellbook.seed import bip39_wordlist

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
SCRIPTS = os.path.join(ROOT, "scripts")
POSIX = os.name == "posix"


def _run(script, args, env=None, cwd=None):
    e = dict(os.environ)
    e["PYTHONPATH"] = os.path.join(ROOT, "src")
    if env:
        e.update(env)
    return subprocess.run([sys.executable, os.path.join(SCRIPTS, script), *args],
                          capture_output=True, text=True, env=e, cwd=cwd,
                          stdin=subprocess.DEVNULL, timeout=120)


def _assert_no_secret_material(text, public_hex=()):
    """No long hex (bar listed public values), no base58 secret, no run of
    BIP-39 words."""
    for h in public_hex:
        text = text.replace(h, "<public>")
    assert not re.search(r"\b[0-9a-fA-F]{64,}\b", text), "64+ hex chars printed"
    assert not re.search(r"\b[1-9A-HJ-NP-Za-km-z]{80,}\b", text), "base58 secret printed"
    words = set(bip39_wordlist())
    for line in text.splitlines():
        toks = [t.lower() for t in re.findall(r"[a-z]+", line)]
        run = 0
        for t in toks:
            run = run + 1 if t in words else 0
            assert run < 8, f"a run of BIP-39 words reached stdout: {line!r}"


def _mode_is_0600(path):
    return stat.S_IMODE(os.stat(path).st_mode) == 0o600


# ------------------------------------------------------------ make_standard_wallet

def test_make_standard_wallet_prints_public_material_only(tmp_path):
    r = _run("make_standard_wallet.py", [str(tmp_path)])
    assert r.returncode == 0, r.stderr
    out = r.stdout + r.stderr
    _assert_no_secret_material(out)
    assert "0x" in out and "txch1" in out and "xch1" in out
    std_seed = tmp_path / "std_seed.key"
    std_entropy = tmp_path / "std_entropy.key"
    assert std_seed.exists() and std_entropy.exists()
    assert len(bytes.fromhex(std_seed.read_text().strip())) == 64
    assert len(bytes.fromhex(std_entropy.read_text().strip())) == 32
    # the secret bytes are in the files and nowhere in the output
    assert std_seed.read_text().strip() not in out
    assert std_entropy.read_text().strip() not in out
    if POSIX:
        assert _mode_is_0600(std_seed) and _mode_is_0600(std_entropy)


def test_make_standard_wallet_refuses_to_overwrite(tmp_path):
    assert _run("make_standard_wallet.py", [str(tmp_path)]).returncode == 0
    r = _run("make_standard_wallet.py", [str(tmp_path)])
    assert r.returncode == 1 and "REFUSED" in r.stderr
    _assert_no_secret_material(r.stdout + r.stderr)


# ------------------------------------------------------------ make_testnet_wallet

def test_make_testnet_wallet_prints_no_secret_and_backup_is_0600(tmp_path):
    home = tmp_path / "home"
    home.mkdir()
    r = _run("make_testnet_wallet.py", [],
             env={"HOME": str(home), "USERPROFILE": str(home)})
    assert r.returncode == 0, r.stderr
    out = r.stdout + r.stderr
    # The puzzle hash is public (it is the address, as 32 bytes of hex).
    m = re.search(r"puzzle_hash:\s+([0-9a-f]{64})", out)
    assert m, out
    _assert_no_secret_material(out, public_hex=(m.group(1),))
    assert "txch1" in out
    seed = home / ".spellbook-testnet" / "seed.key"
    backup = home / "workspace" / "your_files" / "spellbook-testnet-paper-backup.md"
    assert seed.exists() and backup.exists()
    assert seed.read_text().strip() not in out
    words = backup.read_text().splitlines()[-1].split()
    assert len(words) == 24 and all(w in set(bip39_wordlist()) for w in words)
    assert " ".join(words) not in out
    if POSIX:
        assert _mode_is_0600(seed) and _mode_is_0600(backup)


# ------------------------------------------------------------ make_tokens

def test_make_tokens_writes_three_0600_files_and_prints_paths_only(tmp_path):
    prefix = tmp_path / "prefix"
    prefix.mkdir()
    agent_copy = tmp_path / "agent" / "request.token"
    agent_copy.parent.mkdir()
    r = _run("make_tokens.py", [str(prefix), str(agent_copy)])
    assert r.returncode == 0, r.stderr
    req = (prefix / "request.token").read_text()
    app = (prefix / "approve.token").read_text()
    assert len(bytes.fromhex(req)) == 32 and len(bytes.fromhex(app)) == 32
    assert req != app
    assert agent_copy.read_text() == req
    out = r.stdout + r.stderr
    assert req not in out and app not in out
    _assert_no_secret_material(out)
    assert str(agent_copy) in out
    if POSIX:
        for p in (prefix / "request.token", prefix / "approve.token", agent_copy):
            assert _mode_is_0600(p)
    # never overwrites
    r2 = _run("make_tokens.py", [str(prefix), str(agent_copy)])
    assert r2.returncode == 1 and "REFUSED" in r2.stderr
    assert agent_copy.read_text() == req


# ------------------------------------------------------------ export guard

def test_export_guard_refuses_without_a_tty():
    assert "TTY" in exportmod.export_guard(False, True, 1000, [1001])
    assert "TTY" in exportmod.export_guard(True, False, 1000, [1001])
    assert "TTY" in exportmod.export_guard(False, False, 1000, [1001])


def test_export_guard_refuses_the_agent_user():
    reason = exportmod.export_guard(True, True, 1001, [1001, 1002])
    assert "agent" in reason and "1001" in reason


def test_export_guard_allows_the_human_on_a_terminal():
    assert exportmod.export_guard(True, True, 1000, [1001]) is None
    assert exportmod.export_guard(True, True, 0, [1001]) is None
    assert exportmod.export_guard(True, True, 1000, []) is None
    assert exportmod.export_guard(True, True, 1000, None) is None


def test_export_guard_needs_a_login_uid():
    assert exportmod.export_guard(True, True, None, [1001])


def test_export_cli_refuses_on_a_pipe_and_prints_nothing_secret(tmp_path):
    prefix = tmp_path
    r = _run("make_standard_wallet.py", [str(prefix)])
    assert r.returncode == 0, r.stderr
    e = dict(os.environ, PYTHONPATH=os.path.join(ROOT, "src"))
    r = subprocess.run([sys.executable, "-m", "spellbook.cli", "export",
                        "--prefix", str(prefix)],
                       capture_output=True, text=True, env=e,
                       stdin=subprocess.DEVNULL, timeout=120)
    assert r.returncode == 3
    assert "refused" in r.stderr and "TTY" in r.stderr
    _assert_no_secret_material(r.stdout + r.stderr)
    assert (prefix / "std_entropy.key").read_text().strip() not in r.stdout + r.stderr


def test_paper_backup_text_is_words_and_addresses_never_raw_keys():
    kdf_seed = os.urandom(32)
    std_entropy = os.urandom(32)
    text = exportmod.paper_backup_text(kdf_seed, std_entropy)
    assert "SET 1" in text and "SET 2" in text
    assert kdf_seed.hex() not in text and std_entropy.hex() not in text
    assert not re.search(r"\b[0-9a-fA-F]{64,}\b", text)
    assert "written these down" in text
    words = set(bip39_wordlist())
    runs = [l.split() for l in text.splitlines()
            if len(l.split()) == 24 and all(w in words for w in l.split())]
    assert len(runs) == 2


def test_paper_backup_text_handles_a_kdf_only_install():
    text = exportmod.paper_backup_text(os.urandom(32), None, with_addresses=False)
    assert "SET 2" in text and "SET 1" not in text
    with pytest.raises(ValueError):
        exportmod.paper_backup_text(None, None)


def test_installer_never_echoes_secrets():
    sh = open(os.path.join(ROOT, "install.sh"), encoding="utf-8").read()
    for gone in ("STD_BACKUP", "MNEMONIC=", "KDF_KEYS", "REQ_TOKEN=", "APP_TOKEN=",
                 "mnemonic_from_entropy", "scalar_hex", "phantom_backup_secret",
                 "SPELLBOOK_REQUEST_TOKEN="):
        assert gone not in sh, gone
    assert "[ -t 0 ] && [ -t 1 ]" in sh
    assert "spellbook\" export" in sh or "spellbook export" in sh
    assert "make_tokens.py" in sh
